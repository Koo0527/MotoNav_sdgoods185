static int lYearDays(int y){
  int info=LUNAR_INFO[y-1900],s=348,i=0x8000;
  for(;i>0x8;i>>=1) if(info&i) s++;
  if(info&0xf) s += (info&0x10000)?30:29;
  return s;
}
static int leapMonth(int y){ return LUNAR_INFO[y-1900]&0xf; }
static int leapDays(int y){ int lm=leapMonth(y); if(!lm) return 0; return (LUNAR_INFO[y-1900]&0x10000)?30:29; }
static int monthDays(int y,int m){ return (LUNAR_INFO[y-1900]&(0x10000>>m))?30:29; }

static void solar2lunar(int y,int m,int d,int &ly,int &lm,int &ld,bool &isLeap){
  static const int md[]={31,28,31,30,31,30,31,31,30,31,30,31};
  auto days=[&](int yy,int mm,int dd){
    int s=0; for(int i=1900;i<yy;++i) s+=(i%4==0&&(i%100!=0||i%400==0))?366:365;
    for(int i=1;i<mm;++i) s+=md[i-1]+(i==2&&(yy%4==0&&(yy%100!=0||yy%400==0))?1:0);
    return s+dd-1;
  };
  int offset=days(y,m,d)-days(1900,1,31);
  int i=1900,temp=0; isLeap=false;
  for(; i<2101 && offset>0; ++i){ temp=lYearDays(i); offset-=temp; }
  if(offset<0){ offset+=temp; --i; }
  ly=i; int leap=leapMonth(ly); i=1;
  for(; i<13 && offset>0; ++i){
    if(leap>0 && i==(leap+1) && !isLeap){ --i; isLeap=true; temp=leapDays(ly); }
    else { temp=monthDays(ly,i); }
    if(isLeap && i==(leap+1)) isLeap=false;
    offset-=temp;
  }
  if(offset==0 && leap>0 && i==leap+1){ if(isLeap) isLeap=false; else { isLeap=true; --i; } }
  if(offset<0){ offset+=temp; --i; }
  lm=i; ld=offset+1;
}

